function makeText(overrides: Partial<TextElement> & Pick<TextElement, 'id' | 'role' | 'fieldLabel' | 'content'>): TextElement {
  return {
    placeholder: `Masukkan ${overrides.fieldLabel.toLowerCase()}...`,
    visible: true,
    fontFamily: 'Plus Jakarta Sans',
    fontSize: 34,
    fontWeight: 700,
    letterSpacing: 0,
    lineHeight: 1.25,
    textAlign: 'left',
    color: '#ffffff',
    opacity: 1,
    offsetX: 0,
    offsetY: 0,
    rotation: 0,
    uppercase: false,
    maxWidth: 740,
    zIndex: 10,
    ...overrides,
  };
}

function makeShape(overrides: Partial<ShapeElement> & Pick<ShapeElement, 'id' | 'name' | 'kind'>): ShapeElement {
  return {
    visible: true,
    x: 0,
    y: 0,
    width: 680,
    height: 120,
    fillColor: '#092c25',
    fillOpacity: 1,
    strokeColor: '#d9b66d',
    strokeWidth: 0,
    borderRadius: 0,
    rotation: 0,
    zIndex: 1,
    ...overrides,
  };
}

function buildDesign(params: {
  templateId: string;
  category: TemplateCategory;
  composition: LayoutComposition;
  colors: ColorPalette;
  layout?: Partial<LayoutConfig>;
  effects?: Partial<EffectsConfig>;
  animation?: Partial<AnimationConfig>;
  shapes: ShapeElement[];
  texts: TextElement[];
}): LowerThirdDesign {
  return {
    version: 1,
    templateId: params.templateId,
    category: params.category,
    composition: params.composition,
    colors: params.colors,
    layout: { ...DEFAULT_LAYOUT, ...params.layout },
    effects: { ...DEFAULT_EFFECTS, ...params.effects },
    animation: { ...DEFAULT_ANIMATION, ...params.animation },
    shapes: params.shapes,
    texts: params.texts,
    logos: [],
  };
}

